/**
 * Контракт модуля кора (ADR-0001 «модульный кор»).
 *
 * Модуль — внутренняя механика движка: интегрируется НАПРЯМУЮ (in-process,
 * без адаптеров), но наружу отдаёт только декларированный вход/выход:
 *  - вход  = `TConfig` (конвенции/настройки модуля, мержатся поверх дефолтов);
 *  - выход = `TApi` (типизированная поверхность, которую потребляют другие
 *    модули/обёртки).
 *
 * Внешние нужды кора (state, router, …) модуль объявляет через ПОРТЫ
 * (`ports.ts`) — пакеты реализуют адаптеры к портам, импорт реализации
 * пакета внутри модуля запрещён by construction.
 *
 * Сборка движка из модулей (engine assembly) появится вместе со вторым
 * модулем и обёртками — не проектируем DI на один модуль (ADR-0001 §сборка).
 */
export interface IWeberModule<TApi, TConfig = void> {
  /** Уникальное имя модуля, конвенция: `weber:<kebab-name>`. */
  readonly name: `weber:${string}`;
  /** Фабрика инстанса: конфиг (поверх дефолтов модуля) → API. */
  readonly create: (config?: TConfig) => TApi;
}

/**
 * Identity-хелпер объявления модуля: фиксирует shape и даёт вывод типов
 * на месте объявления (без него `create` теряет связь TConfig→TApi у
 * потребителя).
 */
export const defineModule = <TApi, TConfig = void>(
  module: IWeberModule<TApi, TConfig>,
): IWeberModule<TApi, TConfig> => module;
